// Reproducible asset packing. The authored source atlas is retained unmodified.
import {createCanvas,loadImage} from '@napi-rs/canvas';
import {writeFileSync,mkdirSync} from 'node:fs';
const source=await loadImage('src/assets/materials/mythkin-material-atlas-v3.png');
const names=['fur','shag','scales','bark','bone','skin','feathers','cloth','hide'],tiles={};
for(let i=0;i<9;i++){
 const canvas=createCanvas(128,128),ctx=canvas.getContext('2d');
 ctx.drawImage(source,i%3*source.width/3,Math.floor(i/3)*source.height/3,source.width/3,source.height/3,0,0,128,128);
 const rgba=ctx.getImageData(0,0,128,128).data,pixels=new Uint8Array(128*128);
 for(let k=0;k<pixels.length;k++)pixels[k]=Math.round((rgba[k*4]+rgba[k*4+1]+rgba[k*4+2])/3);
 tiles[names[i]]=Buffer.from(pixels).toString('base64');
}
mkdirSync('src/creatures/materials',{recursive:true});
writeFileSync('src/creatures/materials/painted.ts',`// Generated by tests/pack-material-atlas.mjs from the retained authored atlas.\nexport const PAINTED_MATERIALS:Record<string,string>=${JSON.stringify(tiles)};\n`);
console.log('Packed nine authored 128px material tiles; runtime loads synchronously.');
